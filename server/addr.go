package server

import (
	"net"
	"strings"
)

// Return the host a client dials to reach a server listening on host; a server listening on all interfaces is reached over loopback.
func DialHost(host string) string {
	if host == "" {
		return "127.0.0.1"
	}
	ip := net.ParseIP(host)
	if ip == nil || !ip.IsUnspecified() {
		return host
	}
	if ip.To4() != nil {
		return "127.0.0.1"
	}
	return "::1"
}

// Report whether host is reachable only from this machine: "localhost" or a loopback IP.
func IsLoopback(host string) bool {
	if strings.EqualFold(host, "localhost") {
		return true
	}
	ip := net.ParseIP(host)
	return ip != nil && ip.IsLoopback()
}
